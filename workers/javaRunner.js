/**
 * workers/javaRunner.js — Java runner code generator for sandbox
 *
 * Generates the Runner.java that:
 * - Loads the user's Solution class
 * - Finds the `solution` method via reflection
 * - Parses JSON test case inputs into correct Java types
 *   (int, int[], int[][], long[], double[], boolean, String, String[], char[])
 * - Serializes output back to JSON
 * - Outputs a single JSON line: { results: [...] }
 */

'use strict'

function buildJavaRunner(testCases) {
  const tc = JSON.stringify(testCases)
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')

  // Indented Java source lines — much easier to read and edit than one big template literal
  const lines = [
    'import java.lang.reflect.*;',
    'import java.util.*;',
    '',
    'public class Runner {',
    '    public static void main(String[] args) {',
    '        try {',
    '            Class<?> clazz = Class.forName("Solution");',
    '            Object instance = clazz.getDeclaredConstructor().newInstance();',
    '            Method targetMethod = null;',
    '            for (Method m : clazz.getDeclaredMethods()) {',
    '                if (m.getName().equals("solution")) { targetMethod = m; break; }',
    '            }',
    '            if (targetMethod == null) {',
    '                System.out.println("{\\"fatal\\":\\"No method named \'solution\' found\\",\\"results\\":[]}");',
    '                return;',
    '            }',
    '            targetMethod.setAccessible(true);',
    '            Class<?>[] paramTypes = targetMethod.getParameterTypes();',
    '',
    `            String rawTestCases = "${tc}";`,
    '            List<Map<String,Object>> tcs = parseJsonArrayOfObjects(rawTestCases);',
    '            StringBuilder out = new StringBuilder();',
    '            out.append("{\\"results\\":[");',
    '',
    '            for (int i = 0; i < tcs.size(); i++) {',
    '                if (i > 0) out.append(",");',
    '                Map<String,Object> tc = tcs.get(i);',
    '                String inputStr = (String) tc.get("input");',
    '                String expected = (String) tc.get("output");',
    '                boolean isHidden = Boolean.TRUE.equals(tc.get("is_hidden"));',
    '                long start = System.currentTimeMillis();',
    '                try {',
    '                    Object[] parsedArgs = parseArgs("[" + inputStr + "]", paramTypes);',
    '                    Object ret = targetMethod.invoke(instance, parsedArgs);',
    '                    long runtime = System.currentTimeMillis() - start;',
    '                    String actualStr = serializeJson(ret);',
    '                    out.append(String.format(',
    '                        "{\\"index\\":%d,\\"actual\\":%s,\\"expected\\":%s,\\"runtimeMs\\":%d,\\"isHidden\\":%b,\\"error\\":null}",',
    '                        i+1, escapeJsonStr(actualStr), escapeJsonStr(expected), runtime, isHidden));',
    '                } catch (Exception e) {',
    '                    long runtime = System.currentTimeMillis() - start;',
    '                    Throwable cause = e.getCause() != null ? e.getCause() : e;',
    '                    String msg = cause.getMessage() != null ? cause.getMessage() : cause.toString();',
    '                    out.append(String.format(',
    '                        "{\\"index\\":%d,\\"actual\\":null,\\"expected\\":%s,\\"runtimeMs\\":%d,\\"isHidden\\":%b,\\"error\\":%s}",',
    '                        i+1, escapeJsonStr(expected), runtime, isHidden, escapeJsonStr(msg)));',
    '                }',
    '            }',
    '            out.append("]}");',
    '            System.out.println(out.toString());',
    '        } catch (Exception e) {',
    '            String msg = e.getMessage() != null ? e.getMessage() : e.toString();',
    '            System.out.println("{\\"fatal\\":" + escapeJsonStr(msg) + ",\\"results\\":[]}");',
    '        }',
    '    }',
    '',
    '    // ── JSON string escaping ──────────────────────────────────────────',
    '    private static String escapeJsonStr(String s) {',
    '        if (s == null) return "null";',
    '        StringBuilder sb = new StringBuilder();',
    '        sb.append("\\"");',
    '        for (int i = 0; i < s.length(); i++) {',
    '            char c = s.charAt(i);',
    '            if      (c == \'\\\\\')',
    '                sb.append("\\\\\\\\");',
    '            else if (c == \'\\"\') sb.append("\\\\\\"");',
    '            else if (c == \'\\n\') sb.append("\\\\n");',
    '            else if (c == \'\\r\') {}',
    '            else sb.append(c);',
    '        }',
    '        sb.append("\\"");',
    '        return sb.toString();',
    '    }',
    '',
    '    // ── Serialize any Java value back to JSON ────────────────────────',
    '    private static String serializeJson(Object obj) {',
    '        if (obj == null) return "null";',
    '        if (obj instanceof Boolean)  return obj.toString();',
    '        if (obj instanceof Number)   return obj.toString();',
    '        if (obj instanceof String)   return "\\"" + obj + "\\"";',
    '        if (obj instanceof int[]) {',
    '            int[] a = (int[]) obj;',
    '            StringBuilder sb = new StringBuilder("[");',
    '            for (int i = 0; i < a.length; i++) { if (i>0) sb.append(","); sb.append(a[i]); }',
    '            return sb.append("]").toString();',
    '        }',
    '        if (obj instanceof int[][]) {',
    '            int[][] a = (int[][]) obj;',
    '            StringBuilder sb = new StringBuilder("[");',
    '            for (int i = 0; i < a.length; i++) {',
    '                if (i>0) sb.append(",");',
    '                sb.append("[");',
    '                for (int j = 0; j < a[i].length; j++) { if (j>0) sb.append(","); sb.append(a[i][j]); }',
    '                sb.append("]");',
    '            }',
    '            return sb.append("]").toString();',
    '        }',
    '        if (obj instanceof long[]) {',
    '            long[] a = (long[]) obj;',
    '            StringBuilder sb = new StringBuilder("[");',
    '            for (int i = 0; i < a.length; i++) { if (i>0) sb.append(","); sb.append(a[i]); }',
    '            return sb.append("]").toString();',
    '        }',
    '        if (obj instanceof double[]) {',
    '            double[] a = (double[]) obj;',
    '            StringBuilder sb = new StringBuilder("[");',
    '            for (int i = 0; i < a.length; i++) { if (i>0) sb.append(","); sb.append(a[i]); }',
    '            return sb.append("]").toString();',
    '        }',
    '        if (obj instanceof boolean[]) {',
    '            boolean[] a = (boolean[]) obj;',
    '            StringBuilder sb = new StringBuilder("[");',
    '            for (int i = 0; i < a.length; i++) { if (i>0) sb.append(","); sb.append(a[i]); }',
    '            return sb.append("]").toString();',
    '        }',
    '        if (obj instanceof char[]) {',
    '            char[] a = (char[]) obj;',
    '            StringBuilder sb = new StringBuilder("[");',
    '            for (int i = 0; i < a.length; i++) { if (i>0) sb.append(","); sb.append("\\"").append(a[i]).append("\\""); }',
    '            return sb.append("]").toString();',
    '        }',
    '        if (obj instanceof String[]) {',
    '            String[] a = (String[]) obj;',
    '            StringBuilder sb = new StringBuilder("[");',
    '            for (int i = 0; i < a.length; i++) { if (i>0) sb.append(","); sb.append("\\"").append(a[i]).append("\\""); }',
    '            return sb.append("]").toString();',
    '        }',
    '        if (obj instanceof Object[]) {',
    '            Object[] a = (Object[]) obj;',
    '            StringBuilder sb = new StringBuilder("[");',
    '            for (int i = 0; i < a.length; i++) { if (i>0) sb.append(","); sb.append(serializeJson(a[i])); }',
    '            return sb.append("]").toString();',
    '        }',
    '        if (obj instanceof List) {',
    '            List<?> l = (List<?>) obj;',
    '            StringBuilder sb = new StringBuilder("[");',
    '            for (int i = 0; i < l.size(); i++) { if (i>0) sb.append(","); sb.append(serializeJson(l.get(i))); }',
    '            return sb.append("]").toString();',
    '        }',
    '        return obj.toString();',
    '    }',
    '',
    '    // ── Argument parsing: JSON tokens → Java types ──────────────────',
    '    private static Object[] parseArgs(String rawArray, Class<?>[] types) {',
    '        List<String> tokens = splitJsonElements(rawArray.trim());',
    '        Object[] args = new Object[types.length];',
    '        for (int i = 0; i < types.length; i++) {',
    '            String tok = i < tokens.size() ? tokens.get(i).trim() : "";',
    '            args[i] = convertToken(tok, types[i]);',
    '        }',
    '        return args;',
    '    }',
    '',
    '    private static Object convertToken(String tok, Class<?> t) {',
    '        tok = tok.trim();',
    '        // Primitives',
    '        if (t == int.class    || t == Integer.class)  return Integer.parseInt(tok);',
    '        if (t == long.class   || t == Long.class)     return Long.parseLong(tok);',
    '        if (t == double.class || t == Double.class)   return Double.parseDouble(tok);',
    '        if (t == boolean.class|| t == Boolean.class)  return Boolean.parseBoolean(tok);',
    '        if (t == String.class) {',
    '            if (tok.startsWith("\\"") && tok.endsWith("\\"") && tok.length() >= 2)',
    '                return tok.substring(1, tok.length() - 1);',
    '            return tok;',
    '        }',
    '        // 1-D int array',
    '        if (t == int[].class) {',
    '            List<String> items = splitJsonElements(tok);',
    '            int[] res = new int[items.size()];',
    '            for (int i = 0; i < items.size(); i++) res[i] = Integer.parseInt(items.get(i).trim());',
    '            return res;',
    '        }',
    '        // 2-D int array  ← the fix for Merge Intervals etc.',
    '        if (t == int[][].class) {',
    '            List<String> rows = splitJsonElements(tok);',
    '            int[][] res = new int[rows.size()][];',
    '            for (int i = 0; i < rows.size(); i++) {',
    '                List<String> cols = splitJsonElements(rows.get(i).trim());',
    '                res[i] = new int[cols.size()];',
    '                for (int j = 0; j < cols.size(); j++) res[i][j] = Integer.parseInt(cols.get(j).trim());',
    '            }',
    '            return res;',
    '        }',
    '        // 1-D long array',
    '        if (t == long[].class) {',
    '            List<String> items = splitJsonElements(tok);',
    '            long[] res = new long[items.size()];',
    '            for (int i = 0; i < items.size(); i++) res[i] = Long.parseLong(items.get(i).trim());',
    '            return res;',
    '        }',
    '        // 1-D double array',
    '        if (t == double[].class) {',
    '            List<String> items = splitJsonElements(tok);',
    '            double[] res = new double[items.size()];',
    '            for (int i = 0; i < items.size(); i++) res[i] = Double.parseDouble(items.get(i).trim());',
    '            return res;',
    '        }',
    '        // char array  e.g. ["a","b"]',
    '        if (t == char[].class) {',
    '            if (tok.startsWith("\\"") && tok.endsWith("\\"")) {',
    '                // bare string',
    '                return tok.substring(1, tok.length()-1).toCharArray();',
    '            }',
    '            List<String> items = splitJsonElements(tok);',
    '            char[] res = new char[items.size()];',
    '            for (int i = 0; i < items.size(); i++) {',
    '                String s = items.get(i).trim().replace("\\"", "");',
    '                res[i] = s.isEmpty() ? \' \' : s.charAt(0);',
    '            }',
    '            return res;',
    '        }',
    '        // String array',
    '        if (t == String[].class) {',
    '            List<String> items = splitJsonElements(tok);',
    '            String[] res = new String[items.size()];',
    '            for (int i = 0; i < items.size(); i++) {',
    '                String s = items.get(i).trim();',
    '                res[i] = (s.startsWith("\\"") && s.endsWith("\\"")) ? s.substring(1, s.length()-1) : s;',
    '            }',
    '            return res;',
    '        }',
    '        // String[][]',
    '        if (t == String[][].class) {',
    '            List<String> rows = splitJsonElements(tok);',
    '            String[][] res = new String[rows.size()][];',
    '            for (int i = 0; i < rows.size(); i++) {',
    '                List<String> cols = splitJsonElements(rows.get(i).trim());',
    '                res[i] = new String[cols.size()];',
    '                for (int j = 0; j < cols.size(); j++) {',
    '                    String s = cols.get(j).trim();',
    '                    res[i][j] = (s.startsWith("\\"") && s.endsWith("\\"")) ? s.substring(1,s.length()-1) : s;',
    '                }',
    '            }',
    '            return res;',
    '        }',
    '        // List (raw) — used when the method accepts List instead of int[]',
    '        if (t == List.class) {',
    '            List<String> items = splitJsonElements(tok);',
    '            List<Object> res = new ArrayList<>();',
    '            for (String item : items) {',
    '                String s = item.trim();',
    '                if (s.startsWith("[")) {',
    '                    // nested list',
    '                    List<String> sub = splitJsonElements(s);',
    '                    List<Integer> inner = new ArrayList<>();',
    '                    for (String ss : sub) { try { inner.add(Integer.parseInt(ss.trim())); } catch(Exception ignored){} }',
    '                    res.add(inner);',
    '                } else {',
    '                    try { res.add(Integer.parseInt(s)); } catch(Exception e) { res.add(s); }',
    '                }',
    '            }',
    '            return res;',
    '        }',
    '        return tok; // fallback: pass raw string',
    '    }',
    '',
    '    // ── JSON element splitter (depth-aware, quote-aware) ────────────',
    '    private static List<String> splitJsonElements(String arr) {',
    '        List<String> list = new ArrayList<>();',
    '        if (arr.startsWith("[") && arr.endsWith("]"))',
    '            arr = arr.substring(1, arr.length() - 1).trim();',
    '        if (arr.isEmpty()) return list;',
    '        int depth = 0; boolean inQ = false;',
    '        StringBuilder cur = new StringBuilder();',
    '        for (int i = 0; i < arr.length(); i++) {',
    '            char c = arr.charAt(i);',
    '            if (c == \'"\' && (i == 0 || arr.charAt(i-1) != \'\\\\\')) inQ = !inQ;',
    '            if (!inQ) {',
    '                if (c==\'[\'||c==\'{\') depth++;',
    '                else if (c==\']\'||c==\'}\') depth--;',
    '                else if (c==\',\' && depth==0) { list.add(cur.toString().trim()); cur.setLength(0); continue; }',
    '            }',
    '            cur.append(c);',
    '        }',
    '        if (cur.length() > 0) list.add(cur.toString().trim());',
    '        return list;',
    '    }',
    '',
    '    // ── JSON array-of-objects parser (for test case list) ───────────',
    '    private static List<Map<String,Object>> parseJsonArrayOfObjects(String jsonStr) {',
    '        List<Map<String,Object>> list = new ArrayList<>();',
    '        List<String> objs = splitJsonElements(jsonStr);',
    '        for (String objStr : objs) {',
    '            Map<String,Object> map = new HashMap<>();',
    '            if (objStr.startsWith("{") && objStr.endsWith("}")) objStr = objStr.substring(1, objStr.length()-1);',
    '            List<String> pairs = splitJsonElements(objStr);',
    '            for (String pair : pairs) {',
    '                int col = pair.indexOf(\':\'  );',
    '                if (col > 0) {',
    '                    String key = pair.substring(0, col).trim().replace("\\"", "");',
    '                    String val = pair.substring(col+1).trim();',
    '                    if (val.startsWith("\\"") && val.endsWith("\\"")) val = val.substring(1, val.length()-1);',
    '                    if (key.equals("is_hidden")) map.put(key, Boolean.parseBoolean(val));',
    '                    else map.put(key, val);',
    '                }',
    '            }',
    '            list.add(map);',
    '        }',
    '        return list;',
    '    }',
    '}',
  ]

  return lines.join('\n')
}

module.exports = { buildJavaRunner }
